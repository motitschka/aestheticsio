/** Generated by scripts/make-themes.mjs from the aesthetic's Pinterest board. */
export interface Theme {
  id: string
  dark: boolean
  font: string
  body: string
  buttons: ButtonStyle
  layout: LayoutFamily
  icons: IconStyle
  motion: MotionStyle
  pattern: string
  caps: boolean
  /** number of published pins in public/pins/<id>/ */
  pins: number
  colours: ThemeColours
  swatches: string[]
  glow: string
}

const two = (n: number) => String(n).padStart(2, '0')

/** A theme's n-th pin (1-based), wrapping around. */
export const pinUrl = (theme: Pick<Theme, 'id' | 'pins'>, n: number) =>
  `${import.meta.env.BASE_URL}pins/${theme.id}/${two(((n - 1) % Math.max(theme.pins, 1)) + 1)}.webp`

export const pinThumb = (id: string) => `${import.meta.env.BASE_URL}pins/${id}/thumb.webp`

