/** A lesson's theme unlocks when it's learned, and stays unlocked. */
export const themeUnlocked = (e: Entry | undefined) => e?.u === 1 || (e?.lt ?? 0) >= 2

function fontsUrl(theme: Theme) {
  const families = [`family=${encodeURIComponent(theme.font).replace(/%20/g, '+')}`]
  if (theme.body !== 'system') families.push(`family=${encodeURIComponent(theme.body).replace(/%20/g, '+')}:wght@400;600;700`)
  return `https://fonts.googleapis.com/css2?${families.join('&')}&display=swap`
}

/**
 * Applies a theme to the whole app, or restores the default look (null).
 * `root` can be another document's root, e.g. the intro's frame.
 */
export function applyTheme(theme: Theme | null, root: HTMLElement = document.documentElement) {
  const doc = root.ownerDocument
  for (const v of [...Object.values(VARS), ...EXTRA]) root.style.removeProperty(v)
  for (const key of ['buttons', 'layout', 'icons', 'motion', 'pattern', 'caps', 'deco', 'theme']) delete root.dataset[key]
  root.style.removeProperty('color-scheme')
  doc.getElementById('theme-fonts')?.remove()
  const meta = doc.querySelectorAll<HTMLMetaElement>('meta[name="theme-color"]')

  if (!theme) {
    meta.forEach((m) => (m.content = m.media.includes('dark') ? '#141216' : '#f5f1ea'))
    return
  }

  for (const [key, v] of Object.entries(VARS)) root.style.setProperty(v, theme.colours[key as keyof ThemeColours])
  const display = DISPLAY[theme.font] ?? { fallback: 'system-ui, sans-serif', scale: 0.86 }
  root.style.setProperty('--font-display', `'${theme.font}', ${display.fallback}`)
  root.style.setProperty('--display-scale', String(display.scale))
  root.style.setProperty('--font', BODY[theme.body] ?? BODY.system)
  root.style.setProperty('--glow', theme.glow)
  // How much of the background colour lies over the collage.
  root.style.setProperty('--veil', theme.dark ? '72%' : '64%')
  if (theme.dark) root.style.setProperty('--shadow', 'none')
  root.style.setProperty('color-scheme', theme.dark ? 'dark' : 'light')
  root.dataset.buttons = theme.buttons
  root.dataset.layout = theme.layout
  root.dataset.icons = theme.icons
  root.dataset.motion = theme.motion
  root.dataset.pattern = theme.pattern
  if (theme.caps) root.dataset.caps = ''
  if (DECORATIVE.has(theme.font)) root.dataset.deco = ''
  root.dataset.theme = theme.id
  meta.forEach((m) => (m.content = theme.colours.bg))

  const link = doc.createElement('link')
  link.id = 'theme-fonts'
  link.rel = 'stylesheet'
  link.href = fontsUrl(theme)
  doc.head.appendChild(link)
}
